"""
Dashboard AI Summaries -- NFL-wide (not per-league) panels: top real
NFL performers this week, and a funny recap of this week's real NFL
games. Both auto-generated by the scheduler once a week goes final
(see scheduler.py's week-transition hook); the POST endpoints here are
just the manual fallback (e.g. the very first week after this ships,
before any scheduler tick has fired, or if a scheduler pass ever
fails) -- open to any authenticated user rather than commissioner-gated,
since there's no "commissioner" of a global, not-per-league panel.
Rate-limited per-IP for abuse protection; no per-league AI-usage budget
applies here (that's a per-league concept) since a single generation
serves every viewer -- a cached GET has zero marginal LLM cost no
matter how many people load the dashboard.
"""
from fastapi import APIRouter, Depends, HTTPException, Request
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import and_, or_, select

from app.core.database import get_db
from app.core.limiter import limiter
from app.models.user import User
from app.models.nfl_game import NFLGame
from app.models.weekly_top_players_summary import WeeklyTopPlayersSummary
from app.models.weekly_scores_recap import WeeklyScoresRecap
from app.api.deps import get_current_user
from app.api.v1.nfl import current_nfl_week
from app.services import top_performers_service, nfl_schedule_service
from app.services.ai_service import AIService
from app.core.config import settings

router = APIRouter(prefix="/dashboard", tags=["dashboard"])


def _get_ai_service() -> AIService:
    if settings.OPENAI_API_KEY:
        return AIService(api_key=settings.OPENAI_API_KEY, provider="openai")
    if settings.ANTHROPIC_API_KEY:
        return AIService(api_key=settings.ANTHROPIC_API_KEY, provider="anthropic")
    return AIService(api_key=None)


_ESPN_SEASON_TYPE = {"pre": 1, "regular": 2, "post": 3}


async def _current_week_or_none() -> dict | None:
    """The shared current week (GET /nfl/current-week), or None if
    Sleeper can't be reached -- then the panels fall back to the newest
    data they have."""
    try:
        return await current_nfl_week()
    except Exception:
        return None


@router.get("/top-performers")
async def get_top_performers(db: AsyncSession = Depends(get_db)):
    """The newest summary up to the current week -- no week/year params:
    this is an ambient "what's current" panel, not something a viewer
    browses historically (unlike the per-league Digest)."""
    query = select(WeeklyTopPlayersSummary)
    current = await _current_week_or_none()
    if current:
        query = query.where(or_(
            WeeklyTopPlayersSummary.year < current["season"],
            and_(WeeklyTopPlayersSummary.year == current["season"], WeeklyTopPlayersSummary.week <= current["week"]),
        ))
    result = await db.execute(
        query.order_by(
            WeeklyTopPlayersSummary.year.desc(), WeeklyTopPlayersSummary.week.desc(),
        ).limit(1)
    )
    summary = result.scalar_one_or_none()
    if not summary:
        raise HTTPException(status_code=404, detail="No top-performers summary generated yet")
    return {
        "week": summary.week, "year": summary.year, "content": summary.content,
        "top_players": summary.top_players, "created_at": summary.created_at,
    }


@router.post("/top-performers/generate")
@limiter.limit("10/hour")
async def generate_top_performers(
    request: Request,
    week: int,
    year: int,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Manual fallback -- see module docstring. Same shape as the
    scheduler's own auto-generation call."""
    summary = await top_performers_service.generate_and_save_summary(week, year, db)
    return {
        "week": summary.week, "year": summary.year, "content": summary.content,
        "top_players": summary.top_players, "created_at": summary.created_at,
    }


@router.get("/nfl-scores")
async def get_nfl_scores(db: AsyncSession = Depends(get_db)):
    """The current week's games (same week as GET /nfl/current-week) +
    that week's recap (if generated yet -- games can exist before the
    recap does). The scheduler also syncs NEXT week's games for lineups,
    so "newest synced week" ran a week ahead (QA 2026-10-20: Week 8 next
    to Top Performers Week 7); that's only the fallback now, when the
    current week can't be fetched or has no games synced."""
    newest = select(NFLGame).order_by(NFLGame.year.desc(), NFLGame.week.desc()).limit(1)
    latest = None
    current = await _current_week_or_none()
    if current:
        latest = (await db.execute(newest.where(
            NFLGame.year == current["season"], NFLGame.week == current["week"],
            NFLGame.season_type == _ESPN_SEASON_TYPE.get(current["season_type"], 2),
        ))).scalar_one_or_none()
    if not latest:
        latest = (await db.execute(newest)).scalar_one_or_none()
    if not latest:
        raise HTTPException(status_code=404, detail="No NFL game data synced yet")

    games_result = await db.execute(
        select(NFLGame).where(
            NFLGame.year == latest.year, NFLGame.week == latest.week, NFLGame.season_type == latest.season_type,
        ).order_by(NFLGame.kickoff_at)
    )
    games = games_result.scalars().all()

    recap_result = await db.execute(
        select(WeeklyScoresRecap).where(
            WeeklyScoresRecap.week == latest.week, WeeklyScoresRecap.year == latest.year,
        )
    )
    recap = recap_result.scalar_one_or_none()

    return {
        "week": latest.week, "year": latest.year, "season_type": latest.season_type,
        "games": [
            {
                "home_team": g.home_team, "home_team_name": g.home_team_name, "home_score": g.home_score,
                "away_team": g.away_team, "away_team_name": g.away_team_name, "away_score": g.away_score,
                "status_state": g.status_state, "status_detail": g.status_detail, "completed": g.completed,
                "kickoff_at": g.kickoff_at,
            }
            for g in games
        ],
        "recap": recap.content if recap else None,
    }


@router.post("/nfl-scores/generate")
@limiter.limit("10/hour")
async def generate_nfl_scores(
    request: Request,
    week: int,
    year: int,
    season_type: int = 2,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Manual fallback -- syncs fresh games from ESPN, then generates
    the recap from them, same two-step the scheduler's own
    auto-generation hook does."""
    await nfl_schedule_service.sync_week_scoreboard(year, week, season_type, db)
    games = await nfl_schedule_service.get_week_games(year, week, season_type, db)
    if not games:
        raise HTTPException(status_code=404, detail="No games found for that week")

    games_payload = [
        {
            "home_team_name": g.home_team_name, "home_score": g.home_score,
            "away_team_name": g.away_team_name, "away_score": g.away_score,
            "completed": g.completed, "status_detail": g.status_detail,
        }
        for g in games
    ]
    service = _get_ai_service()
    content = await service.generate_nfl_scores_recap(week=week, year=year, games=games_payload)

    existing = await db.execute(
        select(WeeklyScoresRecap).where(WeeklyScoresRecap.week == week, WeeklyScoresRecap.year == year)
    )
    recap = existing.scalar_one_or_none()
    if recap:
        recap.content = content
    else:
        recap = WeeklyScoresRecap(week=week, year=year, content=content)
        db.add(recap)
    await db.commit()

    return {"week": week, "year": year, "content": content}
